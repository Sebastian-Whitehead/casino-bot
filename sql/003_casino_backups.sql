-- Periodic snapshots of the casino bot's local SQLite file (chips, wagers, game history), kept in Supabase.
-- The table holds player data: RLS is on with no policies, so only the postgres/service_role roles can read it.
-- fab_casino_save_backup stores a snapshot and prunes in the same transaction: it keeps at most p_keep newest
-- backups AND drops anything older than p_max_age_hours, but never deletes the newest one (so you always have one).
-- Returns {"id": <new id>, "kept": <rows left>, "deleted": <rows pruned>}.
-- Restore: SELECT data FROM public.casino_backups ORDER BY created_at DESC LIMIT 1;  -- write the bytea out as economy.db
-- P0001 invalid_backup.

CREATE TABLE IF NOT EXISTS public.casino_backups (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  label text,
  size_bytes integer NOT NULL,
  sha256 text NOT NULL,
  data bytea NOT NULL
);
COMMENT ON TABLE public.casino_backups IS 'snapshots of the casino bot economy.db (SQLite); pruned by fab_casino_save_backup';
CREATE INDEX IF NOT EXISTS casino_backups_created_at_idx ON public.casino_backups (created_at DESC, id DESC);
ALTER TABLE public.casino_backups ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.casino_backups FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.fab_casino_save_backup(
  p_data bytea,
  p_label text,
  p_keep integer,
  p_max_age_hours integer
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_id bigint;
  v_deleted bigint;
  v_kept bigint;
BEGIN
  IF p_data IS NULL OR length(p_data) = 0 OR length(p_data) > 52428800 OR
     p_keep IS NULL OR p_keep < 1 OR
     p_max_age_hours IS NULL OR p_max_age_hours < 1 THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'invalid_backup';
  END IF;

  INSERT INTO public.casino_backups (label, size_bytes, sha256, data)
  VALUES (p_label, length(p_data), encode(sha256(p_data), 'hex'), p_data)
  RETURNING id INTO v_id;

  WITH ranked AS (
    SELECT id, created_at, row_number() OVER (ORDER BY created_at DESC, id DESC) AS rn
    FROM public.casino_backups
  ), gone AS (
    DELETE FROM public.casino_backups b
    USING ranked r
    WHERE b.id = r.id
      AND r.rn > 1
      AND (r.rn > p_keep OR r.created_at < now() - make_interval(hours => p_max_age_hours))
    RETURNING b.id
  )
  SELECT count(*) INTO v_deleted FROM gone;

  SELECT count(*) INTO v_kept FROM public.casino_backups;

  RETURN jsonb_build_object('id', v_id, 'kept', v_kept, 'deleted', v_deleted);
END;
$function$;

REVOKE ALL ON FUNCTION public.fab_casino_save_backup(bytea, text, integer, integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.fab_casino_save_backup(bytea, text, integer, integer) TO service_role;
